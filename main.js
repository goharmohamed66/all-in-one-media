'use strict';
const { app, BrowserWindow, shell, ipcMain, dialog, session } = require('electron');
const { autoUpdater } = require('electron-updater');
const path = require('path');
const fs = require('fs');
const os = require('os');
const { fork } = require('child_process');

const PORT = process.env.PORT || 3456;
const APP_URL = `http://127.0.0.1:${PORT}`;
const isDev = process.argv.includes('--dev');

const CONFIG_DIR = path.join(os.homedir(), '.mediagrab');
const SESSION_PARTITION = 'persist:mediagrab'; // shared login session for IG/FB

// Must match the User-Agent the server uses for IG/FB API calls, otherwise
// Instagram treats the reused session cookie as suspicious and logs it out.
const APP_UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';

const PLATFORMS = {
  instagram: {
    loginUrl: 'https://www.instagram.com/accounts/login/',
    homeHint: /instagram\.com\/?($|\?|#)|instagram\.com\/(?!accounts)/,
    keyCookie: 'sessionid',
    domains: ['instagram.com', 'cdninstagram.com'],
  },
  facebook: {
    loginUrl: 'https://www.facebook.com/login/',
    homeHint: /facebook\.com\/?($|\?|#)/,
    keyCookie: 'c_user',
    domains: ['facebook.com', 'fbcdn.net'],
  },
};

let mainWindow = null;
let serverProc = null;

function startServer() {
  return new Promise((resolve, reject) => {
    const serverPath = path.join(__dirname, 'server', 'server.js');
    serverProc = fork(serverPath, [], {
      env: { ...process.env, PORT: String(PORT) },
      stdio: ['ignore', 'pipe', 'pipe', 'ipc'],
    });

    let resolved = false;
    const onData = (buf) => {
      const s = buf.toString();
      process.stdout.write(`[server] ${s}`);
      if (!resolved && /server on http/i.test(s)) {
        resolved = true;
        resolve();
      }
    };
    serverProc.stdout.on('data', onData);
    serverProc.stderr.on('data', (b) => process.stderr.write(`[server] ${b}`));
    serverProc.on('error', reject);
    serverProc.on('exit', (code) => {
      console.log(`[server] exited with code ${code}`);
      if (!resolved) reject(new Error('Server failed to start'));
    });

    // safety timeout
    setTimeout(() => { if (!resolved) { resolved = true; resolve(); } }, 8000);
  });
}

function createWindow() {
  mainWindow = new BrowserWindow({
    width: 1280,
    height: 860,
    minWidth: 980,
    minHeight: 640,
    backgroundColor: '#0a0c16',
    title: 'All In One Media',
    icon: path.join(__dirname, 'server', 'public', 'assets', 'icon.png'),
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
    },
  });

  mainWindow.setMenuBarVisibility(false);
  mainWindow.maximize(); // open filling the whole screen
  mainWindow.loadURL(APP_URL);
  if (isDev) mainWindow.webContents.openDevTools({ mode: 'detach' });

  // open external links in the user's browser
  mainWindow.webContents.setWindowOpenHandler(({ url }) => {
    shell.openExternal(url);
    return { action: 'deny' };
  });

  mainWindow.on('closed', () => (mainWindow = null));
}

